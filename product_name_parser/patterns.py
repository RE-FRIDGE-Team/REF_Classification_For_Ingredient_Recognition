"""
REF 제품명 파싱에 사용되는 정규식 패턴 모음.
Java의 REFProductNameParserAdapter 내 static Pattern 필드에 대응.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[2026-07 개편 — 단어 파먹기(mid-token strip) 버그 수정]

  기존 버그 사례:
    "슈퍼 사우어 웜즈 구미 60봉지입"  →  "… 구미 지입"
        └ QUANTITY_PATTERN 의 단위 '봉'이 '봉지입' 내부의 '봉'에 매칭되어
          "60봉"만 삭제하고 "지입"을 남김.
    "생크림 카스텔라" → "생크림 라"
        └ 브랜드 사전의 '카스텔'이 '카스텔라' 내부에 substring 매칭
          (이 문제는 parser.py 의 브랜드 제거 로직에서 함께 수정).

  수정 원칙:
    1. 수량 단위 뒤에 한글이 더 이어지면 매칭하지 않는다 (단어 안쪽 금지).
       단, '개입/봉지/봉투'처럼 단위 자체가 여러 글자인 경우를 위해
       복합 단위를 단일 단위보다 먼저(alternation 앞쪽에) 배치한다.
    2. 용량 패턴도 단위 뒤 한글/영문 금지(기존 lookahead 유지) + 쉼표 소수점 처리 유지.
    3. 정규식은 '치환 후 잔재'가 아니라 '토큰 전체'를 지우도록 설계한다.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
"""

import re
from typing import List

# ────────────────────────────────────────────────────────────────
# 용량 패턴
#   (숫자)(단위) 형태. 단위 뒤에 한글/영문이 붙으면(예: 300gram, 1리터병)
#   제품명 일부일 수 있으므로 매칭 금지 — 기존 동작 유지.
#   예) "150g" 매칭 O / "150g짜리"의 g 매칭 X
# ────────────────────────────────────────────────────────────────
VOLUME_PATTERN = re.compile(
    r"(\d+(?:[.,]\d+)?)"          # 숫자 (소수점 . 또는 , 허용)
    r"(g|kg|ml|l|L|리터)"          # 용량 단위
    r"(?!\s*\([^)]*\))"           # 바로 뒤 괄호 세트는 별도 패턴이 처리
    r"(?![a-zA-Z가-힣])",          # 단위 뒤에 문자가 이어지면 단어 일부로 간주 → 매칭 금지
    re.IGNORECASE,
)

# ────────────────────────────────────────────────────────────────
# 수량 패턴 ★버그 수정
#   [수정 1] 복합 단위(개입/봉지/봉투/박스/세트/포기)를 alternation 앞에 배치.
#            정규식은 왼쪽 대안을 우선 시도하므로 "60봉지입"은
#            '봉지' → 뒤의 '입'까지 이어서 "60봉지입" 전체가 지워진다.
#   [수정 2] 단위 뒤 한글 금지 lookahead `(?![가-힣])` 추가.
#            '봉'이 '봉지입' 내부에서 부분 매칭하는 것을 원천 차단.
#            (복합 단위가 앞에서 이미 처리되므로 정상 케이스 손실 없음)
#   [수정 3] '봉지입'처럼 복합단위+입 이 붙는 표기를 위해 `(?:입)?` 허용.
# ────────────────────────────────────────────────────────────────
QUANTITY_PATTERN = re.compile(
    r"(?:\d+~)?(\d+)\s*"                                    # (범위 앞부분)? + 수량 숫자
    r"(?:"
    r"개입|봉지입|봉지|봉투|박스|세트|팩입|포기"               # ── 복합(다글자) 단위: 먼저 시도
    r"|개|입|팩|봉|미|구|포|매|정|본|마리|p"                  # ── 단일 단위
    r")"
    r"(?![가-힣])"                                           # ★단위 뒤 한글 금지 → 단어 파먹기 차단
    r"(?!\s*[+x×X])"                                        # 곱셈 표기(3 x 4)의 앞부분은 별도 패턴 처리
)

# ────────────────────────────────────────────────────────────────
# 노이즈 패턴 배열 — Java의 NOISE_PATTERNS[] 와 동일한 순서 유지
# (조기 스킵 최적화 인덱스와 연동되므로 순서 변경 금지)
# ────────────────────────────────────────────────────────────────
NOISE_PATTERNS: List[re.Pattern] = [
    # ── [최고 빈도] 가격 (인덱스 0-3) ──────────────────────────────
    re.compile(r"\d{1,3}(?:,\d{3})*원"),                     # 0: 12,000원
    re.compile(r"\d+%\d{1,3}(?:,\d{3})*원"),                 # 1: 20%12,000원
    re.compile(r"할인\d+%\d{1,3}(?:,\d{3})*원"),             # 2: 할인20%12,000원
    re.compile(                                              # 3: (100g당 1,200원)
        r"\((?:100g|10g|100ml|10ml|1개|1세트|1구|1정|1본)당\s*\d{1,3}(?:,\d{3})*원\)"
    ),

    # ── [고빈도] 대괄호 (인덱스 4) ────────────────────────────────
    re.compile(r"\[[^\]]+\]"),                               # 4: [피코크] 등 전체 제거

    # ── [고빈도] 괄호 상태 (인덱스 5-6) ──────────────────────────
    re.compile(r"\(냉동\)"),                                 # 5
    re.compile(r"\(냉장\)"),                                 # 6

    # ── [중빈도] 평점/리뷰 (인덱스 7) ────────────────────────────
    re.compile(r"[0-9.]+\s*\(\d+\)"),                        # 7: 4.8 (1234)

    # ── [중빈도] 배송 정보 (인덱스 8) ────────────────────────────
    re.compile(
        r"내일\([^)]+\)\s*(?:새벽\s*)?도착\s*보장"
        r"|\d{1,2}/\d{1,2}\([^)]+\)\s*도착\s*예정"
        r"|\(예약일\s*수령\)"
    ),

    # ── [중빈도] 할인 (인덱스 9-10) ──────────────────────────────
    re.compile(r"(?:할인|쿠폰할인|쿠폰)\s*\d+%"),             # 9
    re.compile(r"^\d+%(?=\d{1,3}(?:,\d{3})*원)"),            # 10

    # ── [중빈도] 적립/최저가 (인덱스 11-13) ──────────────────────
    re.compile(r"최대\s*\d{1,3}(?:,\d{3})*원\s*적립"),        # 11
    re.compile(r"최저\d{1,3}(?:,\d{3})*원"),                 # 12
    re.compile(r"\d{1,3}(?:,\d{3})*원\s*와우\s*가입\s*쿠폰"),  # 13

    # ── [중빈도] 증정/한정 (인덱스 14-15) ────────────────────────
    re.compile(r"\+\s*[^,]+증정"),                           # 14
    re.compile(r"\(한정수량\)"),                             # 15

    # ── [저빈도] 원산지 (인덱스 16) ──────────────────────────────
    re.compile(r"\([가-힣A-Z]{2,10}\s*산?\)"),               # 16: (국산)

    # ── [저빈도] 일분 (인덱스 17) ────────────────────────────────
    re.compile(r"\(\d+일분\)"),                              # 17

    # ── [저빈도] 종+택1 (인덱스 18-19) ───────────────────────────
    re.compile(r"\d+종\s*\(택\d+\)"),                        # 18
    re.compile(r"\(택\d+\)"),                                # 19

    # ── [저빈도] 도수 (인덱스 20) ────────────────────────────────
    re.compile(r"\d+도(?=\d{3}|\s|$|,)"),                    # 20

    # ── [저빈도] 시즌/보관 (인덱스 21) ──────────────────────────
    re.compile(r"\([^)]*(?:하우스|햇|후숙|필요|익혀|손질)[^)]*\)"),  # 21

    # ── [저빈도] 과일 등급 (인덱스 22) ──────────────────────────
    re.compile(r"\(로얄과\)"),                               # 22

    # ── [저빈도] 상품 상태 (인덱스 23) ──────────────────────────
    re.compile(r"새\s*상품(?:,\s*반품(?:-미개봉)?)?\s*\(\d+\)"),  # 23

    # ── [저빈도] 등급 (인덱스 24-25) ─────────────────────────────
    re.compile(r",\s*(?:[0-9A-Z+]+)?(?:특등급|상등급|1등급|2등급|등급|1\+등급)(?=\s*$|,|\s+\d)"),
    re.compile(r"\((?:[가-힣A-Z]+)?등급\)"),

    # ── [저빈도] 상태 표현 (인덱스 26) ──────────────────────────
    re.compile(r"\((?:분쇄안함|홀빈|원두|등급\s*:[^)]+|생물)\)"),

    # ── [저빈도] 품종/크기 (인덱스 27-30) ───────────────────────
    re.compile(r"\(품종:[^)]+\)"),
    re.compile(r"\((?:대과|중과|소과|특대과|대|중|소)(?:,\s*\d+~\d+입)?\)"),
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)\s*\((?:대|중|소)(?:과)?\)"),
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)\s*\(\d+~\d+\)"),

    # ── [저빈도] 인증 (인덱스 31) ────────────────────────────────
    re.compile(r"(?:식약청|유기가공식품|HACCP|ISO|GAP|해썹|동물복지|무항생제|무농약)\s*인증"),

    # ── [저빈도] 당도/산도 (인덱스 32-34) ───────────────────────
    re.compile(r"\d+(?:\.\d+)?\s*brix\s*이상"),
    re.compile(r"\d+(?:\.\d+)?\s*brix"),
    re.compile(r"산도\s*\d+(?:\.\d+)?"),

    # ── [저빈도] 조리시간 (인덱스 35) ────────────────────────────
    re.compile(r"\d+분(?:\s*\d+초)?(?![가-힣])"),   # ★수정: '3분카레' 등 뒤 한글이면 매칭 금지

    # ── [저빈도] 영양성분 (인덱스 36) ────────────────────────────
    # ★수정: 'g' 를 alternation 에서 제거 — 용량(g)은 VOLUME_PATTERN 전담.
    #   기존에는 노이즈 제거가 용량 처리보다 먼저 실행되어 "120g"을 먼저
    #   삼켜버렸고, keep-volume / placeholder(VOLTOK) 토글이 무력화됐다.
    #   (제거 모드의 최종 결과는 동일 — 어차피 VOLUME_PATTERN 이 지운다)
    re.compile(r"\d+(?:[.,]\d+)?\s*(?:mg|mcg|kcal|IU)(?![a-zA-Z가-힣])"),

    # ── [저빈도] 개수 범위 앞부분 (인덱스 37) ────────────────────
    # ★수정: 뒤따르는 단위 alternation을 QUANTITY_PATTERN과 동일하게 갱신
    re.compile(r"\d+~(?=\d+\s*(?:개입|봉지입|봉지|봉투|박스|세트|팩입|포기|개|입|팩|봉|미|구|포|매|정|본|마리|p)(?![가-힣]))"),

    # ── [저빈도] x 곱셈 표기 (인덱스 38) ────────────────────────
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)?\s*[xX×]\s*\d+\s*(?:개입?|입|p|팩|ea)?(?![가-힣a-zA-Z])"),

    # ── [저빈도] + 추가 표기 (인덱스 39) ────────────────────────
    re.compile(
        r"\+\s*[^,]+\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)"
        r"\s*[xX×]\s*\d+\s*(?:개입?|입|p|ea)?"
    ),

    # ── [최저빈도] 이중 괄호 (인덱스 40) ────────────────────────
    re.compile(r"\(\([^)]+\)\)"),
]

