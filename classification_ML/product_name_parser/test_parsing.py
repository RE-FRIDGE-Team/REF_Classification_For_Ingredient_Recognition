"""
REFProductNameParser Python 포팅 검증 테스트.
Java 원본 로직과 동일하게 동작하는지 케이스별로 확인한다.
"""

import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from product_name_parser import REFProductNameParser, create_brand_matcher

# ──────────────────────────────────────────────────────────────────
# 테스트용 브랜드 사전
# ──────────────────────────────────────────────────────────────────
SAMPLE_BRANDS = [
    "오뚜기", "농심", "CJ", "풀무원", "동원", "삼양", "롯데", "빙그레",
    "해태", "매일", "서울우유", "남양", "청정원", "사조", "하림",
    "오리온", "크라운", "해표", "대상", "팔도",
]

matcher = create_brand_matcher(SAMPLE_BRANDS)
parser  = REFProductNameParser(brand_matcher=matcher)


def run(label: str, raw: str) -> None:
    result = parser.parse(raw)
    print(f"\n{'─'*60}")
    print(f"케이스 : {label}")
    print(f"원본   : {raw}")
    print(f"정제   : {result.refined_text}")
    print(f"브랜드 : {result.brand_name}")
    print(f"용량   : {result.volume}  ({result.volume_unit})")
    print(f"수량   : {result.quantity}")


# ── 1. 기본 케이스 ────────────────────────────────────────────────
run("기본 파싱",
    "오뚜기 진라면 순한맛 120g 5개입 [코스트코]")

# ── 2. 가격 노이즈 제거 ──────────────────────────────────────────
run("가격 노이즈 제거",
    "농심 신라면 120g 3개입 12,000원 쿠폰할인 10%")

# ── 3. 배송 정보 제거 ────────────────────────────────────────────
run("배송 정보 제거",
    "풀무원 두부 300g 내일(화) 새벽 도착 보장")

# ── 4. 평점/리뷰 제거 ───────────────────────────────────────────
run("평점+리뷰 제거",
    "CJ 비비고 왕교자 700g 4.8 (23456)")

# ── 5. 냉동/냉장 제거 ───────────────────────────────────────────
run("냉동 제거",
    "동원 참치 150g (냉동) 12개입")

# ── 6. 원산지 제거 ───────────────────────────────────────────────
run("원산지 제거",
    "국내산 사과 1.5kg (경북산) 10~12입")

# ── 7. 도수 제거 ────────────────────────────────────────────────
run("도수 제거",
    "참이슬 후레쉬 소주 360ml 25도")

# ── 8. 인증 마크 제거 ───────────────────────────────────────────
run("HACCP 인증 제거",
    "삼양 불닭볶음면 140g 5개입 HACCP 인증")

# ── 9. 용량 단위 정규화 (리터 → l) ─────────────────────────────
run("용량 정규화 리터→l",
    "생수 2리터 6개입")

# ── 10. x 곱셈 표기 제거 ────────────────────────────────────────
run("x 곱셈 표기 제거",
    "롯데 칸쵸 50g x 6개입")

# ── 11. 빈 입력 처리 ────────────────────────────────────────────
run("빈 문자열",
    "")

# ── 12. None 처리 ───────────────────────────────────────────────
result_none = parser.parse(None)
print(f"\n{'─'*60}")
print(f"케이스 : None 입력")
print(f"결과   : {result_none}")

# ── 13. 등급 제거 ───────────────────────────────────────────────
run("등급 표기 제거",
    "한우 등심 200g, 1+등급")

# ── 14. brix 당도 제거 ──────────────────────────────────────────
run("당도 제거",
    "샤인머스켓 1kg 14.5 brix 이상")

# ── 15. 와우 쿠폰 제거 ──────────────────────────────────────────
run("와우 가입 쿠폰 제거",
    "오리온 초코파이 12개입 5,000원 와우 가입 쿠폰")