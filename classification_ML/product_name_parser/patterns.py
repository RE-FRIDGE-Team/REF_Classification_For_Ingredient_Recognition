"""
REF 제품명 파싱에 사용되는 정규식 패턴 모음.
Java의 REFProductNameParserAdapter 내 static Pattern 필드에 100% 대응.
"""

import re
from typing import List

# ────────────────────────────────────────────────────────────────
# 용량 패턴
# Java: (\\d+(?:[.,]\\d+)?)(g|kg|ml|l|L|리터)
#       (?!\\s*\\([^)]*\\))(?![a-zA-Z가-힣])
#       flags: CASE_INSENSITIVE
# ────────────────────────────────────────────────────────────────
VOLUME_PATTERN = re.compile(
    r"(\d+(?:[.,]\d+)?)"
    r"(g|kg|ml|l|L|리터)"
    r"(?!\s*\([^)]*\))"
    r"(?![a-zA-Z가-힣])",
    re.IGNORECASE,
)

# ────────────────────────────────────────────────────────────────
# 수량 패턴
# Java: (?:\\d+~)?(\\d+)\\s*(?:개입?|입|팩|봉|미|구|포|세트|박스|p|매|정|본|마리)
#       (?!\\s*[+x×X])
# ────────────────────────────────────────────────────────────────
QUANTITY_PATTERN = re.compile(
    r"(?:\d+~)?(\d+)\s*"
    r"(?:개입?|입|팩|봉|미|구|포|세트|박스|p|매|정|본|마리)"
    r"(?!\s*[+x×X])"
)

# ────────────────────────────────────────────────────────────────
# 노이즈 패턴 배열 — Java의 NOISE_PATTERNS[] 와 완전 동일한 순서
# 인덱스는 조기 스킵 최적화 로직(removeNoisePatterns)과 연동됨
# ────────────────────────────────────────────────────────────────
NOISE_PATTERNS: List[re.Pattern] = [
    # ── [최고 빈도] 가격 (인덱스 0-3) ──────────────────────────────
    # 0: 가격 (예: 12,000원)
    re.compile(r"\d{1,3}(?:,\d{3})*원"),
    # 1: 퍼센트+가격 (예: 20%12,000원)
    re.compile(r"\d+%\d{1,3}(?:,\d{3})*원"),
    # 2: 할인+퍼센트+가격
    re.compile(r"할인\d+%\d{1,3}(?:,\d{3})*원"),
    # 3: 단가 괄호 (예: (100g당 1,200원))
    re.compile(r"\((?:100g|10g|100ml|10ml|1개|1세트|1구|1정|1본)당\s*\d{1,3}(?:,\d{3})*원\)"),

    # ── [고빈도] 대괄호 (인덱스 4) ────────────────────────────────
    # 4: 대괄호 전체 제거
    re.compile(r"\[[^\]]+\]"),

    # ── [고빈도] 괄호 상태 (인덱스 5-6) ──────────────────────────
    # 5: (냉동)
    re.compile(r"\(냉동\)"),
    # 6: (냉장)
    re.compile(r"\(냉장\)"),

    # ── [중빈도] 평점/리뷰 (인덱스 7) ────────────────────────────
    # 7: 평점 (예: 4.8 (1234))
    re.compile(r"[0-9.]+\s*\(\d+\)"),

    # ── [중빈도] 배송 정보 (인덱스 8) ────────────────────────────
    # 8: 배송 안내 문구
    re.compile(
        r"내일\([^)]+\)\s*(?:새벽\s*)?도착\s*보장"
        r"|\d{1,2}/\d{1,2}\([^)]+\)\s*도착\s*예정"
        r"|\(예약일\s*수령\)"
    ),

    # ── [중빈도] 할인 (인덱스 9-10) ──────────────────────────────
    # 9: 할인/쿠폰할인/쿠폰 퍼센트
    re.compile(r"(?:할인|쿠폰할인|쿠폰)\s*\d+%"),
    # 10: 문자열 앞 퍼센트+가격
    re.compile(r"^\d+%(?=\d{1,3}(?:,\d{3})*원)"),

    # ── [중빈도] 적립/최저가 (인덱스 11-13) ──────────────────────
    # 11: 최대 N원 적립
    re.compile(r"최대\s*\d{1,3}(?:,\d{3})*원\s*적립"),
    # 12: 최저 N원
    re.compile(r"최저\d{1,3}(?:,\d{3})*원"),
    # 13: 와우 가입 쿠폰
    re.compile(r"\d{1,3}(?:,\d{3})*원\s*와우\s*가입\s*쿠폰"),

    # ── [중빈도] 증정/한정 (인덱스 14-15) ────────────────────────
    # 14: + N증정
    re.compile(r"\+\s*[^,]+증정"),
    # 15: (한정수량)
    re.compile(r"\(한정수량\)"),

    # ── [저빈도] 원산지 (인덱스 16) ──────────────────────────────
    # 16: (국산) / (미국산) 등
    re.compile(r"\([가-힣A-Z]{2,10}\s*산?\)"),

    # ── [저빈도] 일분 (인덱스 17) ────────────────────────────────
    # 17: (30일분)
    re.compile(r"\(\d+일분\)"),

    # ── [저빈도] 종+택1 (인덱스 18-19) ───────────────────────────
    # 18: 3종 (택1)
    re.compile(r"\d+종\s*\(택\d+\)"),
    # 19: (택1)
    re.compile(r"\(택\d+\)"),

    # ── [저빈도] 도수 (인덱스 20) ────────────────────────────────
    # 20: 13도 (단, 13도일처럼 붙는 경우 제외)
    re.compile(r"\d+도(?=\d{3}|\s|$|,)"),

    # ── [저빈도] 시즌/보관 (인덱스 21) ──────────────────────────
    # 21: (하우스재배) / (후숙필요) 등
    re.compile(r"\([^)]*(?:하우스|햇|후숙|필요|익혀|손질)[^)]*\)"),

    # ── [저빈도] 과일 등급 (인덱스 22) ──────────────────────────
    # 22: (로얄과)
    re.compile(r"\(로얄과\)"),

    # ── [저빈도] 상품 상태 (인덱스 23) ──────────────────────────
    # 23: 새 상품, 반품-미개봉 (N)
    re.compile(r"새\s*상품(?:,\s*반품(?:-미개봉)?)?\s*\(\d+\)"),

    # ── [저빈도] 등급 (인덱스 24-25) ─────────────────────────────
    # 24: , 1등급 / 특등급 등
    re.compile(r",\s*(?:[0-9A-Z+]+)?(?:특등급|상등급|1등급|2등급|등급|1\+등급)(?=\s*$|,|\s+\d)"),
    # 25: (A등급)
    re.compile(r"\((?:[가-힣A-Z]+)?등급\)"),

    # ── [저빈도] 상태 표현 (인덱스 26) ──────────────────────────
    # 26: (분쇄안함) / (홀빈) / (원두) / (등급:AA) / (생물)
    re.compile(r"\((?:분쇄안함|홀빈|원두|등급\s*:[^)]+|생물)\)"),

    # ── [저빈도] 품종/크기 (인덱스 27-30) ───────────────────────
    # 27: (품종:샤인머스켓)
    re.compile(r"\(품종:[^)]+\)"),
    # 28: (대과) / (소과,10~12입)
    re.compile(r"\((?:대과|중과|소과|특대과|대|중|소)(?:,\s*\d+~\d+입)?\)"),
    # 29: 500g(대과)
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)\s*\((?:대|중|소)(?:과)?\)"),
    # 30: 500g(10~12)
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)\s*\(\d+~\d+\)"),

    # ── [저빈도] 인증 (인덱스 31) ────────────────────────────────
    # 31: HACCP 인증 / 유기가공식품 인증 등
    re.compile(r"(?:식약청|유기가공식품|HACCP|ISO|GAP|해썹|동물복지|무항생제|무농약)\s*인증"),

    # ── [저빈도] 당도/산도 (인덱스 32-34) ───────────────────────
    # 32: 14.5 brix 이상
    re.compile(r"\d+(?:\.\d+)?\s*brix\s*이상"),
    # 33: 14.5brix
    re.compile(r"\d+(?:\.\d+)?\s*brix"),
    # 34: 산도 0.3
    re.compile(r"산도\s*\d+(?:\.\d+)?"),

    # ── [저빈도] 조리시간 (인덱스 35) ────────────────────────────
    # 35: 3분 / 3분 30초
    re.compile(r"\d+분(?:\s*\d+초)?"),

    # ── [저빈도] 영양성분 (인덱스 36) ────────────────────────────
    # 36: 200mg / 50kcal 등 (뒤에 한글·영문 없을 때)
    re.compile(r"\d+(?:[.,]\d+)?\s*(?:mg|mcg|g|kcal|IU)(?![a-zA-Z가-힣])"),

    # ── [저빈도] 개수 범위 앞부분 (인덱스 37) ────────────────────
    # 37: "10~" (10~12개입 같은 범위의 앞부분 제거용)
    re.compile(r"\d+~(?=\d+(?:개입?|입|팩|봉|미|구|포|세트|박스|p|매|정|본|마리))"),

    # ── [저빈도] x 곱셈 표기 (인덱스 38) ────────────────────────
    # 38: 500g x 3개입 / 3 X 30p 등
    re.compile(r"\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)?\s*[xX×]\s*\d+\s*(?:개입?|입|p|팩|ea)?"),

    # ── [저빈도] + 추가 표기 (인덱스 39) ────────────────────────
    # 39: + 뭔가 500g x 3개입
    re.compile(
        r"\+\s*[^,]+\d+(?:[.,]\d+)?(?:g|kg|ml|l|L|리터)"
        r"\s*[xX×]\s*\d+\s*(?:개입?|입|p|ea)?"
    ),

    # ── [최저빈도] 이중 괄호 (인덱스 40) ────────────────────────
    # 40: ((내용))
    re.compile(r"\(\([^)]+\)\)"),
]

