_IDX_BRACKET = 4       # '['  포함 여부로 스킵 판단
_IDX_PAREN_START = 5   # '(' 포함 여부 스킵 구간 시작
_IDX_PAREN_END = 35    # '(' 포함 여부 스킵 구간 끝
_IDX_PRICE_END = 3     # '원' 포함 여부로 스킵 판단 구간 끝
